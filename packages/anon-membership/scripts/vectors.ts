// Hash test vectors, shared by vitest (tests/vectors.json) and nargo test (circuits/lib/src/vectors.nr).
//
//   npx tsx scripts/vectors.ts          writes both files from the TypeScript hashes
//
// The vectors are made once with bb.js and committed. Both test suites then check the same values,
// so a disagreement between the TypeScript and Noir hashes fails one of them.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { fieldToHex, fieldFromBytes } from "../src/field";
import { commitmentOf, initHashing, leafHash, nodeHash, nullifierOf, poseidon2 } from "../src/hash";

export interface Vectors {
  poseidon2: { inputs: string[]; output: string }[];
  commitment: { secret: string; groupId: string; output: string };
  node: { left: string; right: string; output: string };
  leaf: { commitment: string; schemaId: string; validUntilDay: number; registeredDay: number; attrs: string[]; output: string };
  nullifier: { secret: string; scope: string; k: number; output: string }[];
  zeros: string[];
  path: { leaf: string; index: number; siblings: string[]; root: string };
}

export function makeVectors(): Vectors {
  const H = fieldToHex;
  const enc = new TextEncoder();
  const lists: bigint[][] = [[1n], [1n, 2n], [1n, 2n, 3n], [1n, 2n, 3n, 4n], [9n, 8n, 7n, 6n, 5n, 4n, 3n, 2n, 1n]];
  const secret = fieldFromBytes(enc.encode("vector secret"));
  const groupId = fieldFromBytes(enc.encode("did:key:z6MkVector#employees"));
  const scope = fieldFromBytes(enc.encode("vector scope"));
  const c = commitmentOf(secret, groupId);
  const attrs: [bigint, bigint, bigint, bigint] = [fieldFromBytes(enc.encode("RN")), 7n, 20000n, 0n];
  const leaf = { commitment: c, schemaId: 0x5cn, validUntilDay: 20800, registeredDay: 20700, attrs };
  const zeros = [0n];
  for (let i = 0; i < 20; i++) zeros.push(nodeHash(zeros[i], zeros[i]));
  // Leaf 2 of a tree whose leaves are [11, 22, leaf, 0, 0, ...], depth 20.
  const l = leafHash(leaf);
  const siblings = [0n, nodeHash(11n, 22n), ...zeros.slice(2, 20)];
  let node = l;
  const index = 2;
  for (let i = 0; i < 20; i++) node = (index >> i) & 1 ? nodeHash(siblings[i], node) : nodeHash(node, siblings[i]);
  return {
    poseidon2: lists.map((xs) => ({ inputs: xs.map(H), output: H(poseidon2(xs)) })),
    commitment: { secret: H(secret), groupId: H(groupId), output: H(c) },
    node: { left: H(11n), right: H(22n), output: H(nodeHash(11n, 22n)) },
    leaf: { ...leaf, commitment: H(c), schemaId: H(leaf.schemaId), attrs: attrs.map(H), output: H(l) },
    nullifier: [0, 1, 65535].map((k) => ({ secret: H(secret), scope: H(scope), k, output: H(nullifierOf(secret, scope, k)) })),
    zeros: zeros.slice(0, 4).map(H),
    path: { leaf: H(l), index, siblings: siblings.map(H), root: H(node) },
  };
}

/** The Noir test file for `v`. Pure, so a vitest test can check the committed file is current. */
export function vectorsToNoir(v: Vectors): string {
  const arr = (xs: string[]) => `[${xs.join(", ")}]`;
  const out: string[] = [
    "// Generated by scripts/vectors.ts from tests/vectors.json. Do not edit.",
    "use crate::{commitment, h, leaf_hash, merkle_root, nullifier, NODE};",
    "",
  ];
  v.poseidon2.forEach((p, i) => {
    out.push("#[test]", `fn poseidon2_vector_${i}() {`, `    assert(h(${arr(p.inputs)}) == ${p.output});`, "}", "");
  });
  out.push("#[test]", "fn commitment_vector() {", `    assert(commitment(${v.commitment.secret}, ${v.commitment.groupId}) == ${v.commitment.output});`, "}", "");
  out.push("#[test]", "fn node_vector() {", `    assert(h([NODE, ${v.node.left}, ${v.node.right}]) == ${v.node.output});`, "}", "");
  const L = v.leaf;
  out.push(
    "#[test]",
    "fn leaf_vector() {",
    `    assert(leaf_hash(${L.commitment}, ${L.schemaId}, ${L.validUntilDay}, ${L.registeredDay}, ${arr(L.attrs)}) == ${L.output});`,
    "}",
    "",
  );
  v.nullifier.forEach((n, i) => {
    out.push("#[test]", `fn nullifier_vector_${i}() {`, `    assert(nullifier(${n.secret}, ${n.scope}, ${n.k}) == ${n.output});`, "}", "");
  });
  out.push("#[test]", "fn zero_vectors() {", `    let z: [Field; ${v.zeros.length}] = ${arr(v.zeros)};`);
  out.push(`    for i in 1..${v.zeros.length} {`, "        assert(h([NODE, z[i - 1], z[i - 1]]) == z[i]);", "    }", "    assert(z[0] == 0);", "}", "");
  out.push(
    "#[test]",
    "fn path_vector() {",
    `    let siblings: [Field; ${v.path.siblings.length}] = ${arr(v.path.siblings)};`,
    `    assert(merkle_root(${v.path.leaf}, ${v.path.index}, siblings) == ${v.path.root});`,
    "}",
  );
  return out.join("\n") + "\n";
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await initHashing();
  const v = makeVectors();
  writeFileSync(new URL("../tests/vectors.json", import.meta.url), JSON.stringify(v, null, 2) + "\n");
  writeFileSync(new URL("../circuits/lib/src/vectors.nr", import.meta.url), vectorsToNoir(v));
  console.log("wrote tests/vectors.json and circuits/lib/src/vectors.nr");
}
